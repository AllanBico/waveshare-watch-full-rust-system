//! Font mask generation.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{bail, Context, Result};
use fontdue::Font;

use crate::codegen::{font_id_expr, weight_expr, Output};
use crate::manifest::FontSpec;
use crate::pack::pack_4bit;

struct GlyphData {
    codepoint: u32,
    width: u16,
    height: u16,
    xmin: i16,
    ymin: i16,
    advance: u16,
    offset: u32,
    len: u32,
}

struct AssetData {
    font_id: &'static str,
    weight: &'static str,
    size: u16,
    ascent: i16,
    descent: i16,
    line_gap: i16,
    glyphs: Vec<GlyphData>,
}

/// Generates every requested font size.
pub fn generate(root: &Path, specs: &[FontSpec]) -> Result<Vec<Output>> {
    let mut outputs = Vec::new();
    let mut modules = Vec::new();
    for spec in specs {
        let path = root.join("assets").join(&spec.path);
        let data = fs::read(&path)
            .with_context(|| format!("read font {}", path.display()))?;
        let font = Font::from_bytes(data, fontdue::FontSettings::default())
            .map_err(|error| anyhow::anyhow!("parse {}: {error}", path.display()))?;
        for &size in &spec.sizes {
            let name = format!("font_{}_{}_{}", spec.id, spec.weight, size);
            let (asset, masks) = build_asset(&font, spec, size)?;
            outputs.push(Output {
                path: format!("crates/ui/assets/fonts/{name}.bin").into(),
                bytes: masks,
            });
            outputs.push(Output {
                path: format!("crates/ui/src/assets/fonts/{name}.rs").into(),
                bytes: render_asset(&name, &asset).into_bytes(),
            });
            modules.push(name);
        }
    }
    outputs.push(Output {
        path: "crates/ui/src/assets/fonts/mod.rs".into(),
        bytes: render_module(&modules).into_bytes(),
    });
    Ok(outputs)
}

fn build_asset(font: &Font, spec: &FontSpec, size: u16) -> Result<(AssetData, Vec<u8>)> {
    let Some(line) = font.horizontal_line_metrics(f32::from(size)) else {
        bail!("no line metrics for {} at {size}px", spec.path);
    };
    let mut chars = charset(&spec.charset)?;
    chars.sort_unstable();
    chars.dedup();

    let mut glyphs = Vec::new();
    let mut masks = Vec::new();
    for character in chars {
        let (metrics, bitmap) = font.rasterize(character, f32::from(size));
        let packed = pack_4bit(&bitmap);
        let offset = masks.len() as u32;
        masks.extend_from_slice(&packed);
        glyphs.push(GlyphData {
            codepoint: character as u32,
            width: u16::try_from(metrics.width).unwrap_or(u16::MAX),
            height: u16::try_from(metrics.height).unwrap_or(u16::MAX),
            xmin: i16::try_from(metrics.xmin).unwrap_or(i16::MIN),
            ymin: i16::try_from(metrics.ymin).unwrap_or(i16::MIN),
            advance: metrics.advance_width.round().clamp(0.0, f32::from(u16::MAX)) as u16,
            offset,
            len: packed.len() as u32,
        });
    }
    Ok((
        AssetData {
            font_id: font_id_expr(&spec.id)?,
            weight: weight_expr(&spec.weight)?,
            size,
            ascent: line.ascent.round() as i16,
            descent: line.descent.round() as i16,
            line_gap: line.line_gap.round() as i16,
            glyphs,
        },
        masks,
    ))
}

fn render_asset(name: &str, asset: &AssetData) -> String {
    let mut out = String::from(
        "// Generated by tools/assetgen. Do not edit.\n\
         use crate::text::{FontAsset, Glyph};\n\n\
         pub static ASSET: FontAsset = FontAsset {\n",
    );
    writeln!(out, "    font_id: {},", asset.font_id).ok();
    writeln!(out, "    weight: {},", asset.weight).ok();
    writeln!(out, "    size_px: {},", asset.size).ok();
    writeln!(out, "    ascent: {},", asset.ascent).ok();
    writeln!(out, "    descent: {},", asset.descent).ok();
    writeln!(out, "    line_gap: {},", asset.line_gap).ok();
    out.push_str("    glyphs: &[\n");
    for glyph in &asset.glyphs {
        writeln!(
            out,
            "        Glyph {{ codepoint: {}, width: {}, height: {}, xmin: {}, ymin: {}, advance: {}, offset: {}, len: {} }},",
            glyph.codepoint,
            glyph.width,
            glyph.height,
            glyph.xmin,
            glyph.ymin,
            glyph.advance,
            glyph.offset,
            glyph.len
        )
        .ok();
    }
    out.push_str("    ],\n");
    writeln!(
        out,
        "    masks: include_bytes!(\"../../../assets/fonts/{name}.bin\"),"
    )
    .ok();
    out.push_str("};\n");
    out
}

fn render_module(names: &[String]) -> String {
    let mut out = String::from("// Generated by tools/assetgen. Do not edit.\n");
    for name in names {
        writeln!(out, "mod {name};").ok();
    }
    out.push_str("use crate::text::FontAsset;\n\n");
    out.push_str("pub static FONT_ASSETS: &[FontAsset] = &[\n");
    for name in names {
        writeln!(out, "    {name}::ASSET,").ok();
    }
    out.push_str("];\n");
    out
}

fn charset(name: &str) -> Result<Vec<char>> {
    match name {
        "ui" => {
            let mut chars: Vec<char> = (0x20u8..=0x7E).map(char::from).collect();
            chars.extend(['\u{00B0}', '\u{2026}', '\u{2013}', '\u{2014}', '\u{2022}']);
            Ok(chars)
        }
        "numeric" => Ok("0123456789:.-+ %/KBMHz".chars().collect()),
        other => bail!("unknown charset {other}"),
    }
}
