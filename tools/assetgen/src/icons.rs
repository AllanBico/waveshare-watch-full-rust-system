//! Icon mask generation.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use anyhow::{bail, Context, Result};

use crate::codegen::{pascal_case, Output};
use crate::manifest::{IconSpec, IconsSpec};
use crate::pack::pack_4bit;

struct IconMaskData {
    offset: u32,
    len: u32,
}

/// Generates every requested icon size.
pub fn generate(root: &Path, spec: &IconsSpec) -> Result<Vec<Output>> {
    if spec.item.is_empty() {
        bail!("manifest has no icons");
    }
    if spec.sizes.is_empty() {
        bail!("manifest has no icon sizes");
    }
    let mut names = Vec::new();
    for item in &spec.item {
        let name = pascal_case(&item.id);
        if name.is_empty() {
            bail!("icon id {} is empty", item.id);
        }
        if names.contains(&name) {
            bail!("duplicate icon id {}", item.id);
        }
        names.push(name);
    }

    let mut outputs = Vec::new();
    let mut sets = Vec::new();
    for &size in &spec.sizes {
        let (masks, data) = build_size(root, spec, size)?;
        let bin = format!("icons_{size}.bin");
        outputs.push(Output {
            path: format!("crates/ui/assets/icons/{bin}").into(),
            bytes: data,
        });
        sets.push((size, masks));
    }
    outputs.push(Output {
        path: "crates/ui/src/assets/icons.rs".into(),
        bytes: render(&names, &sets).into_bytes(),
    });
    Ok(outputs)
}

fn build_size(
    root: &Path,
    spec: &IconsSpec,
    size: u16,
) -> Result<(Vec<IconMaskData>, Vec<u8>)> {
    let mut masks = Vec::new();
    let mut data = Vec::new();
    for item in &spec.item {
        let coverage = render_icon(root, item, size)?;
        let packed = pack_4bit(&coverage);
        let offset = data.len() as u32;
        data.extend_from_slice(&packed);
        masks.push(IconMaskData {
            offset,
            len: packed.len() as u32,
        });
    }
    Ok((masks, data))
}

fn render_icon(root: &Path, item: &IconSpec, size: u16) -> Result<Vec<u8>> {
    let path = root.join("assets").join(&item.file);
    let svg = fs::read_to_string(&path)
        .with_context(|| format!("read icon {}", path.display()))?;
    let tree = resvg::usvg::Tree::from_str(&svg, &resvg::usvg::Options::default())
        .with_context(|| format!("parse icon {}", path.display()))?;
    let mut pixmap = resvg::tiny_skia::Pixmap::new(u32::from(size), u32::from(size))
        .with_context(|| format!("allocate icon {}", path.display()))?;
    let scale = f32::from(size) / tree.size().width();
    let transform = resvg::tiny_skia::Transform::from_scale(scale, scale);
    resvg::render(&tree, transform, &mut pixmap.as_mut());
    let (pixels, _) = pixmap.data().as_chunks::<4>();
    Ok(pixels.iter().map(|pixel| pixel[3]).collect())
}

fn render(names: &[String], sets: &[(u16, Vec<IconMaskData>)]) -> String {
    let mut out = String::from(
        "// Generated by tools/assetgen. Do not edit.\n\n\
         #[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         #[repr(usize)]\n\
         pub enum IconId {\n",
    );
    for (index, name) in names.iter().enumerate() {
        writeln!(out, "    {name} = {index},").ok();
    }
    out.push_str("}\n\n");
    writeln!(out, "pub const ICON_COUNT: usize = {};\n", names.len()).ok();
    out.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]\n\
         pub struct IconMask {\n\
         \x20   pub offset: u32,\n\
         \x20   pub len: u32,\n\
         \x20   pub width: u16,\n\
         \x20   pub height: u16,\n\
         }\n\n\
         #[derive(Debug, Clone, Copy)]\n\
         pub struct IconSet {\n\
         \x20   pub size_px: u16,\n\
         \x20   pub masks: &'static [IconMask],\n\
         \x20   pub data: &'static [u8],\n\
         }\n\n",
    );
    for (size, masks) in sets {
        writeln!(out, "static ICON_{size}_MASKS: &[IconMask] = &[").ok();
        for mask in masks {
            writeln!(
                out,
                "    IconMask {{ offset: {}, len: {}, width: {size}, height: {size} }},",
                mask.offset, mask.len
            )
            .ok();
        }
        out.push_str("];\n");
        writeln!(
            out,
            "static ICON_{size}_DATA: &[u8] = include_bytes!(\"../../assets/icons/icons_{size}.bin\");\n"
        )
        .ok();
    }
    out.push_str("pub static ICON_SETS: &[IconSet] = &[\n");
    for (size, _) in sets {
        writeln!(
            out,
            "    IconSet {{ size_px: {size}, masks: ICON_{size}_MASKS, data: ICON_{size}_DATA }},"
        )
        .ok();
    }
    out.push_str("];\n");
    out
}
