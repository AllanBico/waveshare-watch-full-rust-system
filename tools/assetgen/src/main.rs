//! Generates compiled-in font and icon assets.

mod codegen;
mod font;
mod icons;
mod manifest;
mod pack;

use std::path::PathBuf;
use std::process::ExitCode;

use anyhow::{Context, Result};

use codegen::Output;
use manifest::Manifest;

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("assetgen: {error:#}");
            ExitCode::FAILURE
        }
    }
}

fn run() -> Result<()> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .canonicalize()
        .context("resolve repository root")?;
    let check = std::env::args().skip(1).any(|arg| arg == "--check");
    let manifest = Manifest::load(&root.join("assets/manifest.toml"))?;

    let mut outputs = font::generate(&root, &manifest.font)?;
    outputs.extend(icons::generate(&root, &manifest.icons)?);
    outputs.push(Output {
        path: "crates/ui/src/assets/mod.rs".into(),
        bytes: module().into_bytes(),
    });

    if check {
        codegen::check_all(&root, &outputs)?;
    } else {
        codegen::write_all(&root, &outputs)?;
    }
    codegen::report_sizes(&outputs)
}

fn module() -> String {
    "// Generated by tools/assetgen. Do not edit.\n\
     mod fonts;\n\
     mod icons;\n\n\
     pub use fonts::FONT_ASSETS;\n\
     pub use icons::{IconId, IconMask, IconSet, ICON_COUNT, ICON_SETS};\n"
        .to_owned()
}
