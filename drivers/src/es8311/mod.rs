//! ES8311 audio codec driver.
//!
//! Configures the playback path for 16 kHz, 16-bit I2S with MCLK supplied by
//! the SoC at 256 × Fs (4.096 MHz). The codec is an I2S slave; the ESP32-S3
//! generates MCLK, BCLK, and LRCK.
//!
//! Register values follow the ES8311 datasheet and the vendor sequence. The
//! clock divider is `DIV_PRE = 1`, not the sample code's `DIV_PRE = 2`: with
//! 4.096 MHz MCLK the latter leaves the DAC below its required 256 × LRCK
//! ratio.

use embedded_hal::i2c::I2c;
use hal::Audio;

mod error;
mod regs;

#[cfg(test)]
mod tests;

pub use error::Es8311Error;

use regs::*;

/// Sample rate this driver is configured for.
pub const SAMPLE_RATE_HZ: u32 = 16_000;
/// MCLK generated by the SoC for this sample rate.
pub const MCLK_HZ: u32 = SAMPLE_RATE_HZ * 256;

/// An ES8311 codec on a shared I2C bus.
pub struct Es8311<I> {
    i2c: I,
    address: u8,
}

impl<I: I2c> Es8311<I> {
    /// Creates a driver for the codec at `address`. No hardware is touched
    /// until [`Audio::init`].
    pub const fn new(i2c: I, address: u8) -> Self {
        Self { i2c, address }
    }

    /// Reads the chip identity register.
    pub fn read_chip_id(&mut self) -> Result<u8, Es8311Error<I::Error>> {
        self.read_reg(CHIP_ID1)
    }

    fn reset(&mut self) -> Result<(), Es8311Error<I::Error>> {
        self.write_reg(RESET, RESET_ALL)?;
        self.write_reg(RESET, RESET_RELEASE)?;
        self.write_reg(RESET, POWER_ON)
    }

    fn configure_clock(&mut self) -> Result<(), Es8311Error<I::Error>> {
        self.write_reg(CLOCK_MANAGER_01, CLOCK_SOURCE_MCLK)?;
        self.update_reg(CLOCK_MANAGER_02, CLOCK_02_CLEAR, CLOCK_02_SET)?;
        self.write_reg(CLOCK_MANAGER_03, CLOCK_03_VALUE)?;
        self.write_reg(CLOCK_MANAGER_04, CLOCK_04_VALUE)?;
        self.write_reg(CLOCK_MANAGER_05, CLOCK_05_VALUE)?;
        self.update_reg(CLOCK_MANAGER_06, CLOCK_06_CLEAR, CLOCK_06_SET)?;
        self.update_reg(CLOCK_MANAGER_07, CLOCK_07_CLEAR, CLOCK_07_SET)?;
        self.write_reg(CLOCK_MANAGER_08, CLOCK_08_VALUE)
    }

    fn configure_format(&mut self) -> Result<(), Es8311Error<I::Error>> {
        self.write_reg(SDP_IN, SDP_16_BIT_I2S)?;
        self.write_reg(SDP_OUT, SDP_16_BIT_I2S)
    }

    fn power_up(&mut self) -> Result<(), Es8311Error<I::Error>> {
        self.write_reg(SYSTEM_0D, SYSTEM_0D_POWER_UP)?;
        self.write_reg(SYSTEM_0E, SYSTEM_0E_POWER_UP)?;
        self.write_reg(SYSTEM_12, SYSTEM_12_DAC_ON)?;
        self.write_reg(SYSTEM_13, SYSTEM_13_HP_DRIVE)?;
        self.write_reg(ADC_1C, ADC_EQ_BYPASS)?;
        self.write_reg(DAC_37, DAC_EQ_BYPASS)
    }

    fn read_reg(&mut self, reg: u8) -> Result<u8, Es8311Error<I::Error>> {
        let mut value = [0u8; 1];
        self.i2c
            .write_read(self.address, &[reg], &mut value)
            .map_err(Es8311Error::Bus)?;
        Ok(value[0])
    }

    fn write_reg(&mut self, reg: u8, value: u8) -> Result<(), Es8311Error<I::Error>> {
        self.i2c
            .write(self.address, &[reg, value])
            .map_err(Es8311Error::Bus)
    }

    fn update_reg(&mut self, reg: u8, clear: u8, set: u8) -> Result<(), Es8311Error<I::Error>> {
        let value = (self.read_reg(reg)? & !clear) | (set & clear);
        self.write_reg(reg, value)
    }
}

impl<I: I2c> Audio for Es8311<I> {
    type Error = Es8311Error<I::Error>;

    fn init(&mut self) -> Result<(), Self::Error> {
        let id = self.read_chip_id()?;
        if id != CHIP_ID1_VALUE {
            return Err(Es8311Error::BadChipId(id));
        }
        self.reset()?;
        self.configure_clock()?;
        self.configure_format()?;
        self.power_up()?;
        self.set_volume(100)?;
        self.unmute()
    }

    fn set_volume(&mut self, percent: u8) -> Result<(), Self::Error> {
        let value = volume_register(percent).map_err(Es8311Error::InvalidVolume)?;
        self.write_reg(DAC_32, value)
    }

    fn mute(&mut self) -> Result<(), Self::Error> {
        self.update_reg(DAC_31, DAC_MUTE, DAC_MUTE)
    }

    fn unmute(&mut self) -> Result<(), Self::Error> {
        self.update_reg(DAC_31, DAC_MUTE, 0)
    }

    fn shutdown(&mut self) -> Result<(), Self::Error> {
        self.write_reg(DAC_32, 0)?;
        self.update_reg(DAC_31, DAC_MUTE, DAC_MUTE)?;
        self.write_reg(SYSTEM_13, 0)?;
        self.write_reg(SYSTEM_12, SYSTEM_12_DAC_OFF)?;
        self.update_reg(SYSTEM_0E, SYSTEM_0E_POWER_DOWN, SYSTEM_0E_POWER_DOWN)?;
        self.write_reg(SYSTEM_0D, SYSTEM_0D_POWER_DOWN)?;
        self.write_reg(RESET, RESET_RELEASE)
    }
}

fn volume_register(percent: u8) -> Result<u8, u8> {
    if percent > 100 {
        return Err(percent);
    }
    Ok(((u16::from(percent) * u16::from(DAC_ZERO_DB)) / 100) as u8)
}
